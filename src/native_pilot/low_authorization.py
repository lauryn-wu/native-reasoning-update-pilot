"""Per-dispatch authorization for the bounded low-effort checkpoint follow-up."""
from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path

from .budget import (
    CAP_MICRO_USD, LOW_EFFORT_CAP_MICRO_USD, LOW_EFFORT_DURATION_SECONDS,
    LOW_EFFORT_SCOPE_ID, Ledger, reservation,
)
from .provider import (
    MODEL, SHARED_LEDGER_PATH, ProviderFailure, build_low_request, validate_low_response,
)
from .runner import require_campaign_lock
from .util import canonical


def require_execution(*, policy, manifest, ledger, campaign_guard,
                      request=None, execution_context=None):
    """Validate the frozen scope, historical checkpoints and one reserved send.

    Earlier completed follow-ups are checked for protocol validity, never answer
    correctness. All branches fork the independently verified historical high
    initial; no response generated by this scope can become a new checkpoint.
    """
    from .low_effort import AUTHORIZATION, ROOT, TASK_IDS, load_frozen, make_schedule, verify_initials

    if (not isinstance(policy, Mapping) or policy.get("paid_execution_allowed") is not False
            or policy.get("protocol_smoke") is not None
            or policy.get("low_effort_followup") != AUTHORIZATION):
        raise ProviderFailure("paid_execution_policy_hold", uncertain_charge=False)
    try:
        frozen = load_frozen(ROOT / "manifests/pilot-v7.json")
        if (not isinstance(manifest, Mapping) or manifest != frozen
                or frozen.get("execution_scope") != "low_effort_followup"
                or frozen.get("low_effort_authorization") != AUTHORIZATION
                or frozen.get("version") != "pilot-v7"
                or frozen.get("status") != "frozen" or frozen.get("blockers") != []
                or frozen.get("paid_execution_allowed") is not False
                or frozen.get("hard_budget_usd") != 40
                or frozen.get("settings") != {"model": MODEL, "reasoning_effort": "low",
                                             "max_output_tokens": 32768}
                or [task["task_id"] for task in frozen["tasks"]] != list(TASK_IDS)
                or AUTHORIZATION.get("authorization_id") != LOW_EFFORT_SCOPE_ID):
            raise ValueError("Unexpected low-effort manifest")
        schedule = make_schedule(frozen["tasks"])
        if (frozen.get("schedule") != schedule or len(schedule) != 24
                or any(call["condition"] not in {"updated_retained", "updated_dropped", "fresh"}
                       for call in schedule)):
            raise ValueError("Unexpected low-effort schedule")
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        raise ProviderFailure("low_followup_manifest_not_authorized", uncertain_charge=False) from None

    if not isinstance(ledger, Ledger) or ledger.path.resolve() != SHARED_LEDGER_PATH.resolve():
        raise ProviderFailure("shared_budget_ledger_required", uncertain_charge=False)
    try:
        require_campaign_lock(campaign_guard, ledger)
    except RuntimeError:
        raise ProviderFailure("active_campaign_lock_required", uncertain_charge=False) from None
    if not any(row[1] == "main" and SHARED_LEDGER_PATH.resolve() == Path(row[2]).resolve()
               for row in ledger.db.execute("PRAGMA database_list").fetchall()):
        raise ProviderFailure("shared_budget_ledger_required", uncertain_charge=False)
    try:
        checkpoints = verify_initials(ledger, frozen)
        if not isinstance(checkpoints, Mapping) or set(checkpoints) != set(TASK_IDS):
            raise ValueError("Missing historical checkpoint")
        # Validate every inherited high-effort request/response even on initial
        # client construction; the verifier additionally binds their raw hashes.
        for task in frozen["tasks"]:
            build_low_request(task, "updated_retained", checkpoints[task["task_id"]])
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        raise ProviderFailure("low_followup_initials_unverified", uncertain_charge=False) from None

    manifest_hash = frozen["manifest_sha256"]
    ledger.bind_scope(LOW_EFFORT_SCOPE_ID, manifest_hash,
        cap_micro_usd=LOW_EFFORT_CAP_MICRO_USD, duration_seconds=LOW_EFFORT_DURATION_SECONDS)
    binding = "execution_authorization/" + LOW_EFFORT_SCOPE_ID
    with ledger.transaction():
        ledger.db.execute("INSERT OR IGNORE INTO meta VALUES (?,?)", (binding, manifest_hash))
        if ledger.db.execute("SELECT value FROM meta WHERE key=?", (binding,)).fetchone()[0] != manifest_hash:
            raise ProviderFailure("low_followup_authorization_already_bound", uncertain_charge=False)
    if request is None:
        return

    required = {"manifest_sha256", "task_id", "call_id", "condition", "sample", "attempt"}
    if (not isinstance(execution_context, Mapping) or set(execution_context) != required
            or any(not isinstance(execution_context[key], str)
                   for key in ("manifest_sha256", "task_id", "call_id", "condition"))):
        raise ProviderFailure("scoped_dispatch_metadata_required", uncertain_charge=False)
    context = execution_context
    allowed = {manifest_hash + "/" + call["call_id"]: call for call in schedule}
    call = allowed.get(context["call_id"])
    if (call is None or context["manifest_sha256"] != manifest_hash
            or any(context[key] != call[key] for key in ("task_id", "condition", "sample"))
            or type(context["sample"]) is not int or type(context["attempt"]) is not int
            or context["attempt"] not in (1, 2)):
        raise ProviderFailure("low_followup_call_not_authorized", uncertain_charge=False)
    call_index = schedule.index(call)
    grouped = {}
    for prior in ledger.rows(manifest_hash):
        if (prior["call_id"] not in allowed or prior["kind"] != "low_effort_followup"
                or type(prior["attempt"]) is not int or prior["attempt"] not in (1, 2)):
            raise ProviderFailure("low_followup_ledger_contains_unauthorized_calls", uncertain_charge=False)
        if schedule.index(allowed[prior["call_id"]]) > call_index:
            raise ProviderFailure("low_followup_schedule_not_a_prefix", uncertain_charge=False)
        grouped.setdefault(prior["call_id"], []).append(prior)
        try:
            outcome = json.loads(prior["outcome"]) if prior["outcome"] else {}
            if not isinstance(outcome, dict):
                raise ValueError("Invalid outcome")
        except (TypeError, ValueError):
            raise ProviderFailure("low_followup_history_unverified", uncertain_charge=False) from None
        if prior["state"] == "provider_failure" or outcome.get("status") == "provider_failure":
            raise ProviderFailure("low_followup_stopped_after_provider_failure", uncertain_charge=False)
        if outcome.get("status") == "protocol_failure":
            raise ProviderFailure("low_followup_stopped_after_protocol_failure", uncertain_charge=False)
    for attempts in grouped.values():
        attempts.sort(key=lambda row: row["attempt"])
        if ([row["attempt"] for row in attempts] != list(range(1, len(attempts) + 1))
                or (len(attempts) == 2 and attempts[0]["state"] != "transport_uncertain")):
            raise ProviderFailure("low_followup_transport_retry_not_authorized", uncertain_charge=False)
    tasks = {task["task_id"]: task for task in frozen["tasks"]}
    for earlier in schedule[:call_index]:
        key = manifest_hash + "/" + earlier["call_id"]
        history = grouped.get(key, [])
        previous = history[-1] if history else None
        if not previous or previous["state"] != "completed":
            raise ProviderFailure("low_followup_schedule_not_a_prefix", uncertain_charge=False)
        try:
            value, outcome = json.loads(previous["response"]), json.loads(previous["outcome"])
            checkpoint = None if earlier["condition"] == "fresh" else checkpoints[earlier["task_id"]]
            expected = build_low_request(tasks[earlier["task_id"]], earlier["condition"], checkpoint)
            if (outcome.get("protocol_valid") is not True or value.get("status") in ("failed", "cancelled")
                    or not validate_low_response(value, expected["reasoning"]["context"])["valid"]
                    or any(row["request"] != canonical(expected).decode() for row in history)):
                raise ValueError("Invalid prior response or request")
            for row in history:
                claim = ledger.db.execute("SELECT value FROM meta WHERE key=?", (
                    "provider_dispatch/" + key + "/" + str(row["attempt"]),)).fetchone()
                if not claim or claim[0] != manifest_hash:
                    raise ValueError("Prior attempt lacks its dispatch claim")
        except (TypeError, ValueError, KeyError, AttributeError):
            raise ProviderFailure("low_followup_history_unverified", uncertain_charge=False) from None
    checkpoint = None if call["condition"] == "fresh" else checkpoints[call["task_id"]]
    expected = build_low_request(tasks[call["task_id"]], call["condition"], checkpoint)
    if request != expected:
        raise ProviderFailure("low_followup_request_not_frozen", uncertain_charge=False)
    history = grouped.get(context["call_id"], [])
    row = history[-1] if history else None
    if (not row or row["state"] != "dispatched" or row["attempt"] != context["attempt"]
            or any(attempt["request"] != canonical(request).decode() for attempt in history)
            or row["reserved"] < reservation(request, checkpoint)["micro_usd"]
            or ledger.total() > CAP_MICRO_USD):
        raise ProviderFailure("low_followup_dispatch_reservation_required", uncertain_charge=False)
    if context["attempt"] == 2:
        claim = ledger.db.execute("SELECT value FROM meta WHERE key=?", (
            "provider_dispatch/" + context["call_id"] + "/1",)).fetchone()
        if not claim or claim[0] != manifest_hash:
            raise ProviderFailure("low_followup_transport_retry_not_authorized", uncertain_charge=False)
    # BudgetRefused propagates unchanged: an elapsed window is not a transport
    # failure and must not acquire a retry. This check also latches clock faults.
    ledger.assert_scope_dispatch(LOW_EFFORT_SCOPE_ID, manifest_hash, context["call_id"], context["attempt"])
    claim = "provider_dispatch/" + context["call_id"] + "/" + str(context["attempt"])
    with ledger.transaction():
        if ledger.db.execute("SELECT value FROM meta WHERE key=?", (claim,)).fetchone():
            raise ProviderFailure("low_followup_attempt_already_dispatched", uncertain_charge=False)
        ledger.db.execute("INSERT INTO meta VALUES (?,?)", (claim, manifest_hash))
